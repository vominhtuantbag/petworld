lines.push(`  if (env) {`);
lines.push(`    for (const slug of slugs) {`);
lines.push(`      const hit = pickPath(\`\${env}/\${mapFolder}/\${slug}\`, slug, canonical);`);
lines.push(`      if (hit) return hit;`);
lines.push(`    }`);
lines.push(`    if (mapFolder !== 'map1') {`);
lines.push(`      for (const slug of slugs) {`);
lines.push(`        const hit = pickPath(\`\${env}/map1/\${slug}\`, slug, canonical);`);
lines.push(`        if (hit) return hit;`);
