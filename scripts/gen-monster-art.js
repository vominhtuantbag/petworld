lines.push(`  const canonical = KIND_ALIAS[kindId] ?? kindId;`);
lines.push(`  const slugs = slugCandidates(canonical);`);
lines.push(`  if (!slugs.length) return null;`);
lines.push(``);
lines.push(`  const envFromZone = environmentFromZoneId(context?.zoneId);`);
lines.push(`  const envFromCtx = assetEnvForFauna(context?.environment);`);
lines.push(`  const envFromKind = assetEnvForFauna(faunaFromKindId(canonical));`);
lines.push(`  const env = envFromZone ?? envFromCtx ?? envFromKind;`);
lines.push(``);
lines.push(`  const mapFromCtx = normalizeMapFolder(context?.mapFolder);`);
lines.push(`  const mapFromZone = mapFolderFromZoneId(context?.zoneId);`);
lines.push(`  const mapFolder = mapFromCtx ?? mapFromZone ?? 'map1';`);
