lines.push(`      const bp = preferred && b.startsWith(preferred) ? 0 : 1;`);
lines.push(`      return ap - bp || a.localeCompare(b);`);
lines.push(`    });`);
lines.push(`    for (const key of keys) {`);
lines.push(`      const hit = pickPath(key, slug, canonical);`);
lines.push(`      if (hit) return hit;`);
lines.push(`    }`);
lines.push(`  }`);
lines.push(``);
lines.push(`  for (const slug of slugs) {`);
lines.push(`    const source = BY_FLAT_SLUG[slug];`);
